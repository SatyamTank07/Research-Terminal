class AnnualFinancialInput(BaseModel):
    """
    Extracted annual financial data for a single fiscal year.
    Equipped with AliasChoices to accept standard US-GAAP / 10-K synonyms.
    """
    fiscal_year: int = Field(
        ...,
        description="4-digit fiscal year (e.g. 2025)",
        validation_alias=AliasChoices("fiscal_year", "year", "fy")
    )
    revenue: float = Field(
        ...,
        description="Total net sales or revenues in $ millions",
        validation_alias=AliasChoices("revenue", "total_revenue", "net_sales", "total_net_sales", "sales")
    )
    gross_profit: float = Field(
        ...,
        description="Gross profit / gross margin in $ millions",
        validation_alias=AliasChoices("gross_profit", "gross_margin", "gross_income")
    )
    operating_income: float = Field(
        ...,
        description="Operating income / EBIT in $ millions",
        validation_alias=AliasChoices("operating_income", "ebit", "operating_profit", "income_from_operations")
    )
    net_income: float = Field(
        ...,
        description="Net income attributable to common shareholders in $ millions",
        validation_alias=AliasChoices("net_income", "net_earnings", "net_profit")
    )
    operating_cash_flow: float = Field(
        ...,
        description="Net cash generated by operating activities in $ millions",
        validation_alias=AliasChoices(
            "operating_cash_flow",
            "cash_from_operations",
            "operating_activities_cash_flow",
            "cash_provided_by_operating_activities",
            "net_cash_provided_by_operating_activities"
        )
    )
    capital_expenditures: float = Field(
        ...,
        description=(
            "Capital expenditures (CapEx / additions to property, plant & equipment) in $ millions. "
            "Must be passed as a positive magnitude representing cash outflows."
        ),
        validation_alias=AliasChoices(
            "capital_expenditures",
            "capex",
            "payments_for_acquisition_of_property_plant_and_equipment",
            "purchases_of_property_and_equipment",
            "additions_to_property_plant_and_equipment"
        )
    )
    # Secondary / Optional line items for tax derivation and forensic analysis
    pretax_income: Optional[float] = Field(
        None,
        description="Income before provision for income taxes in $ millions",
        validation_alias=AliasChoices(
            "pretax_income",
            "income_before_taxes",
            "income_before_provision_for_income_taxes",
            "income_before_income_tax",
            "earnings_before_taxes"
        )
    )
    income_tax_expense: Optional[float] = Field(
        None,
        description="Provision for income taxes / tax expense in $ millions",
        validation_alias=AliasChoices(
            "income_tax_expense",
            "provision_for_income_taxes",
            "tax_expense",
            "income_tax_provision"
        )
    )
    depreciation_amortization: Optional[float] = Field(
        None,
        description="Depreciation and amortization expense in $ millions (for EBITDA)",
        validation_alias=AliasChoices(
            "depreciation_amortization",
            "depreciation_and_amortization",
            "dna",
            "depreciation"
        )
    )
    accounts_receivable: Optional[float] = Field(
        None,
        description="Net accounts receivable in $ millions (for Tier 2 forensic check)",
        validation_alias=AliasChoices("accounts_receivable", "ar", "accounts_receivable_net")
    )
    inventories: Optional[float] = Field(
        None,
        description="Total inventory in $ millions (for Tier 3 forensic check; omit if N/A)",
        validation_alias=AliasChoices("inventories", "inventory")
    )

    @field_validator("capital_expenditures")
    @classmethod
    def validate_capex_positive(cls, v: float) -> float:
        """
        Safety guard: Rejects negative CapEx values.
        Enforces consistency with Zero Mathematical Hallucination: CapEx must be passed
        as a positive magnitude representing cash outflows (e.g. 12715.0, not -12715.0).
        Prevents misreading asset sale proceeds as CapEx or silent sign masking.
        """
        if v < 0:
            raise ValueError(
                f"capital_expenditures ({v:,.2f}) must be passed as a positive magnitude "
                f"representing cash outflows (e.g. 12715.0 instead of -12715.0). "
                f"If this line item represents proceeds from asset sales, do not pass it as CapEx."
            )
        return float(v)


class BalanceSheetInput(BaseModel):
    """
    Extracted balance sheet snapshot for the latest fiscal year.
    Equipped with validation guard on diluted shares to prevent scale errors.
    """
    fiscal_year: int = Field(
        ...,
        description="4-digit fiscal year of the balance sheet (e.g. 2025)",
        validation_alias=AliasChoices("fiscal_year", "year", "fy")
    )
    cash_and_equivalents: float = Field(
        ...,
        ge=0.0,
        description="Cash and cash equivalents in $ millions",
        validation_alias=AliasChoices("cash_and_equivalents", "cash", "cash_and_cash_equivalents")
    )
    marketable_securities: float = Field(
        0.0,
        ge=0.0,
        description="Total liquid marketable securities (current + non-current liquid holdings) in $ millions",
        validation_alias=AliasChoices("marketable_securities", "short_term_investments", "liquid_investments")
    )
    short_term_debt: float = Field(
        0.0,
        ge=0.0,
        description="Commercial paper, current portion of long-term debt, and short-term borrowings in $ millions",
        validation_alias=AliasChoices(
            "short_term_debt",
            "commercial_paper",
            "current_debt",
            "current_portion_of_debt",
            "current_portion_of_term_debt"
        )
    )
    long_term_debt: float = Field(
        0.0,
        ge=0.0,
        description="Non-current term debt and long-term borrowings in $ millions",
        validation_alias=AliasChoices("long_term_debt", "term_debt", "non_current_debt")
    )
    stockholders_equity: float = Field(
        ...,
        description="Total stockholders' / shareholders' equity in $ millions (can be negative)",
        validation_alias=AliasChoices("stockholders_equity", "shareholders_equity", "total_equity", "equity")
    )
    diluted_shares_outstanding: float = Field(
        ...,
        description="Diluted common shares outstanding in MILLIONS (e.g. 15004.7, NOT 15004697 or 15004697000)",
        validation_alias=AliasChoices("diluted_shares_outstanding", "diluted_shares", "shares_outstanding")
    )
    current_assets: Optional[float] = Field(
        None,
        ge=0.0,
        description="Total current assets in $ millions (for Current Ratio)",
        validation_alias=AliasChoices("current_assets", "total_current_assets")
    )
    current_liabilities: Optional[float] = Field(
        None,
        ge=0.0,
        description="Total current liabilities in $ millions (for Current Ratio)",
        validation_alias=AliasChoices("current_liabilities", "total_current_liabilities")
    )

    @field_validator("diluted_shares_outstanding")
    @classmethod
    def validate_shares_scale(cls, v: float) -> float:
        """
        Safety guard: Rejects share counts passed in thousands or raw units (> 100,000).
        Enforces user direction: Do not silently auto-normalize; guide the caller explicitly.
        """
        if v > 100_000.0:
            raise ValueError(
                f"diluted_shares_outstanding ({v:,.2f}) appears to be passed in thousands or raw units. "
                f"All shares must be standardized to MILLIONS (e.g. 15004.7 instead of 15004697). "
                f"Please divide by 1,000 (or 1,000,000) and retry."
            )
        if v <= 0:
            raise ValueError(f"diluted_shares_outstanding must be strictly positive (> 0), got: {v}")
        return float(v)


