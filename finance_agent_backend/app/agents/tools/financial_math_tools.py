# 6. Core Sequenced Audit Engine
# ==============================================================================
def audit_financial_metrics(
    annual_financials: List[AnnualFinancialInput],
    balance_sheet: BalanceSheetInput,
) -> Dict[str, Any]:
    """
    Pure Python coordinator executing financial ratio calculations and forensic screening.
    Returns fully validated, structured dictionary conforming to FinancialAuditResult.
    """
    logger.info(
        f"audit_financial_metrics: Auditing {len(annual_financials)} fiscal years for "
        f"FY{balance_sheet.fiscal_year} (Shares: {balance_sheet.diluted_shares_outstanding:,.2f}M)"
    )

    # 1. Deterministic Ratio Calculations (validates contiguous years & temporal matching)
    calc_results = calculate_financial_ratios(
        annual_financials=annual_financials,
        balance_sheet=balance_sheet,
    )

    # 2. Sequenced Forensic Accounting Checks
    forensic_flags = detect_forensic_red_flags(
        annual_inputs=annual_financials,
        multi_year_history=calc_results["multi_year_history"],
        balance_sheet=balance_sheet,
    )

    audit_result = FinancialAuditResult(
        multi_year_history=calc_results["multi_year_history"],
        balance_sheet=calc_results["balance_sheet"],
        profitability_and_return_ratios=calc_results["profitability_and_return_ratios"],
        solvency_and_liquidity_ratios=calc_results["solvency_and_liquidity_ratios"],
        forensic_red_flags=forensic_flags,
    )

    logger.info(
        f"audit_financial_metrics: Completed audit. Net Debt: ${audit_result.balance_sheet.net_debt:,.2f}M "
        f"({'Net Cash' if audit_result.balance_sheet.net_cash_position else 'Net Debt'}) | "
        f"ROIC: {audit_result.profitability_and_return_ratios.roic_pct}% | "
        f"Red flags detected: {len(forensic_flags)}"
    )

    return audit_result.model_dump()


