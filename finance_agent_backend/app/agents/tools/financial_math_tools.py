# 4. Internal Function 1: Financial Ratios Calculation
# ==============================================================================
def calculate_financial_ratios(
    annual_financials: List[AnnualFinancialInput],
    balance_sheet: BalanceSheetInput,
) -> Dict[str, Any]:
    """
    Computes multi-year margins, Free Cash Flow, YoY growth rates, effective tax rate,
    ROIC, ROE, Net Debt, and solvency ratios from verified line items.
    Enforces contiguous fiscal years and temporal matching with the balance sheet.
    """
    if not annual_financials:
        raise ValueError("annual_financials must contain at least one fiscal year.")

    # 1. Temporal Integrity & Contiguity Validation Guard
    years = sorted(f.fiscal_year for f in annual_financials)
    expected_contiguous = list(range(years[0], years[-1] + 1))
    if years != expected_contiguous:
        raise ValueError(
            f"annual_financials must contain contiguous fiscal years with no gaps. "
            f"Supplied: {years}, expected: {expected_contiguous}"
        )
    if balance_sheet.fiscal_year != years[-1]:
        raise ValueError(
            f"balance_sheet.fiscal_year ({balance_sheet.fiscal_year}) must match the latest "
            f"annual_financials fiscal year ({years[-1]})."
        )

    # Chronological sort: T-2, T-1, T_0
    sorted_years = sorted(annual_financials, key=lambda x: x.fiscal_year)

    multi_year_history: List[YearFinancialsResult] = []
    prev_year: Optional[AnnualFinancialInput] = None
    prev_fcf: Optional[float] = None

    for f in sorted_years:
        rev = _validate_finite_number(f.revenue, f"revenue ({f.fiscal_year})")
        gp = _validate_finite_number(f.gross_profit, f"gross_profit ({f.fiscal_year})")
        ebit = _validate_finite_number(f.operating_income, f"operating_income ({f.fiscal_year})")
        ni = _validate_finite_number(f.net_income, f"net_income ({f.fiscal_year})")
        ocf = _validate_finite_number(f.operating_cash_flow, f"operating_cash_flow ({f.fiscal_year})")
        capex = _validate_finite_number(f.capital_expenditures, f"capital_expenditures ({f.fiscal_year})")
        
        fcf = round(ocf - capex, 2)

        # Profitability Margins
        gm_pct = round((gp / rev) * 100.0, 2) if rev != 0 else 0.0
        om_pct = round((ebit / rev) * 100.0, 2) if rev != 0 else 0.0
        nm_pct = round((ni / rev) * 100.0, 2) if rev != 0 else 0.0
        fcf_conv = round((fcf / ni) * 100.0, 2) if ni != 0 else None

        # YoY Growth Rates
        rev_growth = None
        ebit_growth = None
        fcf_growth = None

        if prev_year is not None:
            if prev_year.revenue != 0:
                rev_growth = round(((rev - prev_year.revenue) / abs(prev_year.revenue)) * 100.0, 2)
            if prev_year.operating_income != 0:
                ebit_growth = round(((ebit - prev_year.operating_income) / abs(prev_year.operating_income)) * 100.0, 2)
            if prev_fcf is not None and prev_fcf != 0:
                fcf_growth = round(((fcf - prev_fcf) / abs(prev_fcf)) * 100.0, 2)

        multi_year_history.append(
            YearFinancialsResult(
                fiscal_year=f.fiscal_year,
                revenue=rev,
                gross_profit=gp,
                gross_margin_pct=gm_pct,
                operating_income=ebit,
                operating_margin_pct=om_pct,
                net_income=ni,
                net_margin_pct=nm_pct,
                operating_cash_flow=ocf,
                capital_expenditures=capex,
                free_cash_flow=fcf,
                fcf_conversion_pct=fcf_conv,
                revenue_growth_pct=rev_growth,
                operating_income_growth_pct=ebit_growth,
                fcf_growth_pct=fcf_growth,
            )
        )

        prev_year = f
        prev_fcf = fcf

    # Latest year references
    latest_input = sorted_years[-1]
    latest_res = multi_year_history[-1]

    # Effective Tax Rate Derivation with Provenance Flags
    tax_rate = 0.21
    tax_source = "statutory_default_not_provided"

    if latest_input.pretax_income is not None and latest_input.income_tax_expense is not None:
        pt_income = latest_input.pretax_income
        tax_exp = latest_input.income_tax_expense

        if pt_income <= 0:
            tax_rate = 0.21
            tax_source = "statutory_fallback_due_to_pretax_loss"
        elif tax_exp < 0:
            tax_rate = 0.21
            tax_source = "statutory_fallback_due_to_tax_benefit"
        else:
            tax_rate = round(tax_exp / pt_income, 4)
            tax_source = "derived_from_10k"

    # Liquidity & Solvency Bridge (Consistent definition of Liquid Cash)
    total_liquid = round(balance_sheet.cash_and_equivalents + balance_sheet.marketable_securities, 2)
    total_debt = round(balance_sheet.short_term_debt + balance_sheet.long_term_debt, 2)
    net_debt = round(total_debt - total_liquid, 2)
    net_cash_pos = bool(net_debt < 0)

    # NOPAT & Invested Capital
    nopat = round(latest_res.operating_income * (1.0 - tax_rate), 2)
    invested_capital = round(total_debt + balance_sheet.stockholders_equity - total_liquid, 2)

    # Book Equity Guard: Suppress ROE, ROIC, and Debt/Equity if equity <= 0
    equity = balance_sheet.stockholders_equity
    equity_status = "positive_book_equity"
    roic_pct = None
    roe_pct = None
    total_debt_equity = None

    if equity < 0:
        equity_status = "negative_book_equity_ratios_suppressed"
        logger.warning(
            f"calculate_financial_ratios: Stockholders' equity is negative (${equity:,.1f}M). "
            f"Suppressing ROIC, ROE, and Debt/Equity to prevent distortion."
        )
    elif equity == 0:
        equity_status = "zero_book_equity_ratios_suppressed"
    else:
        # Standard capital return calculation when equity > 0
        if invested_capital > 0:
            roic_pct = round((nopat / invested_capital) * 100.0, 2)
        roe_pct = round((latest_res.net_income / equity) * 100.0, 2)
        total_debt_equity = round(total_debt / equity, 2)

    # EBITDA & Solvency
    ebitda = None
    net_debt_ebitda = None
    ebitda_interp = "ebitda_not_available"

    if latest_input.depreciation_amortization is not None:
        ebitda = round(latest_res.operating_income + latest_input.depreciation_amortization, 2)
        if ebitda > 0:
            net_debt_ebitda = round(net_debt / ebitda, 2)
            ebitda_interp = "net_cash_surplus" if net_cash_pos else "leverage_ratio"
        elif ebitda < 0:
            ebitda_interp = "negative_ebitda"

    # Current Ratio: Explicit is not None checks
    current_ratio = None
    if balance_sheet.current_assets is not None and balance_sheet.current_liabilities is not None:
        if balance_sheet.current_liabilities > 0:
            current_ratio = round(balance_sheet.current_assets / balance_sheet.current_liabilities, 2)

    bs_res = BalanceSheetResult(
        fiscal_year=balance_sheet.fiscal_year,
        cash_and_equivalents=balance_sheet.cash_and_equivalents,
        marketable_securities=balance_sheet.marketable_securities,
        total_liquid_cash=total_liquid,
        short_term_debt=balance_sheet.short_term_debt,
        long_term_debt=balance_sheet.long_term_debt,
        total_debt=total_debt,
        net_debt=net_debt,
        net_cash_position=net_cash_pos,
        stockholders_equity=balance_sheet.stockholders_equity,
        diluted_shares_outstanding=balance_sheet.diluted_shares_outstanding,
        current_assets=balance_sheet.current_assets,
        current_liabilities=balance_sheet.current_liabilities,
    )

    profit_res = ProfitabilityRatiosResult(
        effective_tax_rate_pct=round(tax_rate * 100.0, 2),
        tax_rate_source=tax_source,
        equity_status=equity_status,
        nopat=nopat,
        invested_capital=invested_capital,
        roic_pct=roic_pct,
        roe_pct=roe_pct,
        latest_gross_margin_pct=latest_res.gross_margin_pct,
        latest_operating_margin_pct=latest_res.operating_margin_pct,
        latest_net_margin_pct=latest_res.net_margin_pct,
    )

    solv_res = SolvencyRatiosResult(
        net_debt_to_ebitda=net_debt_ebitda,
        net_debt_to_ebitda_interpretation=ebitda_interp,
        current_ratio=current_ratio,
        total_debt_to_equity=total_debt_equity,
    )

    return {
        "multi_year_history": multi_year_history,
        "balance_sheet": bs_res,
        "profitability_and_return_ratios": profit_res,
        "solvency_and_liquidity_ratios": solv_res,
    }


