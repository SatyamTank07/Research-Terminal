# 5. Internal Function 2: Sequenced Forensic Red-Flag Detector
# ==============================================================================
def detect_forensic_red_flags(
    annual_inputs: List[AnnualFinancialInput],
    multi_year_history: List[YearFinancialsResult],
    balance_sheet: Optional[BalanceSheetInput] = None,
) -> List[str]:
    """
    Performs algorithmic forensic accounting checks sequenced by data availability:
    - Tier 1a: Net Income vs. Operating Cash Flow divergence.
    - Tier 1b: Chronically weak Free Cash Flow conversion (< 70% across all profitable years).
    - Tier 1c: Chronic OCF deficit (OCF < Net Income in every reported year).
    - Tier 1d: Negative book equity warning.
    - Tier 2 (When AR is present): YoY Accounts Receivable Growth vs. Revenue Growth.
    - Tier 3 (When Inventory is present): YoY Inventory Growth vs. Revenue Growth.
    """
    red_flags: List[str] = []

    # Map inputs by fiscal year for quick lookup
    input_map = {f.fiscal_year: f for f in annual_inputs}

    # --------------------------------------------------------------------------
    # Tier 1a: Net Income vs. OCF Divergence
    # --------------------------------------------------------------------------
    for idx in range(1, len(multi_year_history)):
        cur = multi_year_history[idx]
        prev = multi_year_history[idx - 1]

        ni_change = cur.net_income - prev.net_income
        ocf_change = cur.operating_cash_flow - prev.operating_cash_flow

        ni_growth_pct = (ni_change / abs(prev.net_income)) * 100.0 if prev.net_income != 0 else 0.0
        ocf_growth_pct = (ocf_change / abs(prev.operating_cash_flow)) * 100.0 if prev.operating_cash_flow != 0 else 0.0

        # Divergence: Net Income increased while OCF declined
        if ni_growth_pct > 0.0 and ocf_growth_pct < 0.0:
            red_flags.append(
                f"EARNINGS QUALITY DIVERGENCE (FY{cur.fiscal_year}): Net income increased by "
                f"+{ni_growth_pct:.2f}% (${prev.net_income:,.1f}M -> ${cur.net_income:,.1f}M) while operating "
                f"cash flow declined by {ocf_growth_pct:.2f}% (${prev.operating_cash_flow:,.1f}M -> "
                f"${cur.operating_cash_flow:,.1f}M). This indicates potential accrual expansion, non-operating "
                f"gains, or significant tax/working capital cash timing outflows."
            )

    # --------------------------------------------------------------------------
    # Tier 1b: Chronically Weak FCF Conversion (< 70% across all profitable years)
    # --------------------------------------------------------------------------
    positive_ni_years = [
        h for h in multi_year_history
        if h.net_income > 0 and h.fcf_conversion_pct is not None
    ]
    if len(positive_ni_years) >= 2 and all(h.fcf_conversion_pct < 70.0 for h in positive_ni_years):
        avg_conv = sum(h.fcf_conversion_pct for h in positive_ni_years) / len(positive_ni_years)
        red_flags.append(
            f"WEAK CASH CONVERSION WARNING: Free cash flow conversion (FCF / Net Income) has been chronically "
            f"weak (< 70%) across all reported years with positive earnings (averaging {avg_conv:.1f}%), "
            f"signaling high capital intensity or poor earnings-to-cash realization."
        )

    # --------------------------------------------------------------------------
    # Tier 1c: Chronic OCF Deficit (OCF < Net Income across all years)
    # --------------------------------------------------------------------------
    if len(multi_year_history) >= 2:
        chronic_deficit = all(h.operating_cash_flow < h.net_income for h in multi_year_history)
        if chronic_deficit:
            red_flags.append(
                "CHRONIC ACCRUAL DEFICIT: Operating cash flow was strictly lower than net income in every "
                "reported fiscal year, signaling persistently low cash conversion quality."
            )

    # --------------------------------------------------------------------------
    # Tier 1d: Negative Book Equity Warning
    # --------------------------------------------------------------------------
    if balance_sheet is not None and balance_sheet.stockholders_equity < 0:
        red_flags.append(
            f"NEGATIVE BOOK EQUITY WARNING: Stockholders' equity is negative (${balance_sheet.stockholders_equity:,.1f}M). "
            f"Return on Equity (ROE), Return on Invested Capital (ROIC), and Debt-to-Equity have been suppressed as uninterpretable."
        )

    # --------------------------------------------------------------------------
    # Tier 2: Accounts Receivable vs. Revenue Growth Divergence
    # --------------------------------------------------------------------------
    for idx in range(1, len(multi_year_history)):
        cur_yr = multi_year_history[idx].fiscal_year
        prev_yr = multi_year_history[idx - 1].fiscal_year

        cur_inp = input_map.get(cur_yr)
        prev_inp = input_map.get(prev_yr)

        if cur_inp and prev_inp:
            if cur_inp.accounts_receivable is not None and prev_inp.accounts_receivable is not None:
                prev_ar = prev_inp.accounts_receivable
                cur_ar = cur_inp.accounts_receivable

                if prev_ar > 0:
                    ar_growth_pct = ((cur_ar - prev_ar) / prev_ar) * 100.0
                    rev_growth_pct = multi_year_history[idx].revenue_growth_pct or 0.0
                    spread = ar_growth_pct - rev_growth_pct

                    # If AR grew > 15% faster than revenue
                    if spread > 15.0 and ar_growth_pct > 5.0:
                        red_flags.append(
                            f"RECEIVABLES DIVERGENCE (FY{cur_yr}): Accounts receivable grew by +{ar_growth_pct:.2f}% "
                            f"(${prev_ar:,.1f}M -> ${cur_ar:,.1f}M), significantly outpacing revenue growth of "
                            f"{rev_growth_pct:+.2f}% (spread of {spread:.1f}%). This may signal aggressive "
                            f"revenue recognition, channel stuffing, or customer payment delays."
                        )

    # --------------------------------------------------------------------------
    # Tier 3: Inventory vs. Revenue Growth Divergence
    # --------------------------------------------------------------------------
    for idx in range(1, len(multi_year_history)):
        cur_yr = multi_year_history[idx].fiscal_year
        prev_yr = multi_year_history[idx - 1].fiscal_year

        cur_inp = input_map.get(cur_yr)
        prev_inp = input_map.get(prev_yr)

        if cur_inp and prev_inp:
            if cur_inp.inventories is not None and prev_inp.inventories is not None:
                prev_inv = prev_inp.inventories
                cur_inv = cur_inp.inventories

                # Only run check if the firm actually carries inventory (bypasses software/services)
                if prev_inv > 0 and cur_inv > 0:
                    inv_growth_pct = ((cur_inv - prev_inv) / prev_inv) * 100.0
                    rev_growth_pct = multi_year_history[idx].revenue_growth_pct or 0.0
                    spread = inv_growth_pct - rev_growth_pct

                    # If Inventory grew > 20% faster than revenue
                    if spread > 20.0 and inv_growth_pct > 10.0:
                        red_flags.append(
                            f"INVENTORY ACCUMULATION WARNING (FY{cur_yr}): Inventory increased by +{inv_growth_pct:.2f}% "
                            f"(${prev_inv:,.1f}M -> ${cur_inv:,.1f}M), substantially exceeding revenue growth of "
                            f"{rev_growth_pct:+.2f}% (spread of {spread:.1f}%). This may indicate product "
                            f"obsolescence risk, supply-chain bottlenecks, or slowing end-market sell-through."
                        )

    return red_flags


